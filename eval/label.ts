/**
 * Human labelling (SPEC.md §21, §25 Day 5).
 *
 * §25's Day 5 exit criterion is "**Kushagra labels 60 fixtures**", and the
 * paragraph under the milestone table says Day 5 "is still not Claude Code's
 * work". So the ground truth is a person's, and this file is a notebook, not a
 * classifier:
 *
 *   * no code path writes a label without one being supplied;
 *   * there is no default, no inference, no "probably rejected";
 *   * an existing label is never silently replaced;
 *   * `labelled_by` is required, because an unattributable ground truth cannot
 *     be questioned later;
 *   * `labelled_at` is generated by the tool rather than typed, so it records
 *     when the decision was recorded rather than what someone remembered.
 *
 * §4's `eval_label` has two values, `qualified` and `rejected`. The three-valued
 * `verdict` enum — which includes `uncertain` — is what a *predictor* may
 * answer; it is not a label a human may give, because §21's corpus is ground
 * truth and "I am not sure" is not ground truth. A fixture a human cannot
 * decide should not be in the corpus.
 */
import { canonicalJson } from './canonical';
import { listFixtureDomains, loadFixture, readLabels, readSplit } from './corpus';
import { labelsPath, relativeToRepo, writeAtomic } from './paths';
import { SanitiserRejection } from './sanitise-snapshot';
import {
  fixtureLabel,
  labelsFile,
  type EvalLabel,
  type FixtureLabel,
  type LabelsFile,
} from './schemas';

/** §25's Day 5 exit criterion, as a number the tool refuses to round up. */
export const REQUIRED_LABEL_COUNT = 60;

export interface LabelInput {
  readonly fixtureSet: string;
  readonly domain: string;
  readonly label: EvalLabel;
  readonly reasonCodes: readonly string[];
  readonly disqualifier: string | null;
  readonly labelledBy: string;
  /** Injected so tests are deterministic; the CLI passes the real clock. */
  readonly now?: Date;
  /** Required to replace a label that already exists. */
  readonly replace?: boolean;
}

export interface LabelResult {
  readonly domain: string;
  readonly label: FixtureLabel;
  readonly replaced: FixtureLabel | undefined;
  readonly path: string;
}

/**
 * Records one human decision.
 *
 * The fixture is loaded first, so a label cannot be written for a domain that
 * has no frozen evidence behind it — a label with nothing to label is a row that
 * will fail the runner much later, somewhere less obvious.
 */
export function recordLabel(input: LabelInput): LabelResult {
  // Throws if the fixture does not exist, is misfiled, or fails its digest.
  loadFixture(input.fixtureSet, input.domain);

  const existing = readLabels(input.fixtureSet);
  const previous = existing.labels[input.domain];
  if (previous !== undefined && input.replace !== true) {
    throw new SanitiserRejection(
      'already_labelled',
      `${input.domain} is already labelled "${previous.label}" by ${previous.labelled_by} ` +
        `at ${previous.labelled_at}. Pass --replace to overrule a human decision`,
    );
  }

  const label = fixtureLabel.parse({
    label: input.label,
    reason_codes: [...input.reasonCodes],
    disqualifier: input.disqualifier,
    labelled_by: input.labelledBy,
    labelled_at: (input.now ?? new Date()).toISOString(),
  });

  const next: LabelsFile = labelsFile.parse({
    fixture_set: input.fixtureSet,
    labels: { ...existing.labels, [input.domain]: label },
  });

  const path = labelsPath(input.fixtureSet);
  writeAtomic(path, canonicalJson(next));

  return { domain: input.domain, label, replaced: previous, path: relativeToRepo(path) };
}

export interface LabelStatus {
  readonly fixtureSet: string;
  readonly total: number;
  readonly labelled: number;
  readonly unlabelled: number;
  readonly qualified: number;
  readonly rejected: number;
  readonly dev: number;
  readonly holdout: number;
  readonly unassigned: number;
  /** The §25 exit criterion, and whether it is met. Never rounded up. */
  readonly required: number;
  readonly exitCriterionMet: boolean;
  readonly unlabelledDomains: readonly string[];
  readonly labellers: readonly string[];
}

/**
 * The progress report §25's exit criterion needs.
 *
 * `exitCriterionMet` is `labelled >= 60` and nothing else. It is not "enough for
 * now", it does not scale to the corpus size, and it does not become true at 59.
 * Day 5 is not exited until a person has made sixty decisions.
 */
export function labelStatus(fixtureSet: string): LabelStatus {
  const domains = listFixtureDomains(fixtureSet);
  const { labels } = readLabels(fixtureSet);
  const { assignments } = readSplit(fixtureSet);

  const labelled = domains.filter((domain) => labels[domain] !== undefined);
  const labellers = new Set<string>();
  let qualified = 0;
  let rejected = 0;
  for (const domain of labelled) {
    const entry = labels[domain];
    if (entry === undefined) {
      continue;
    }
    labellers.add(entry.labelled_by);
    if (entry.label === 'qualified') {
      qualified += 1;
    } else {
      rejected += 1;
    }
  }

  return {
    fixtureSet,
    total: domains.length,
    labelled: labelled.length,
    unlabelled: domains.length - labelled.length,
    qualified,
    rejected,
    dev: domains.filter((domain) => assignments[domain] === 'dev').length,
    holdout: domains.filter((domain) => assignments[domain] === 'holdout').length,
    unassigned: domains.filter((domain) => assignments[domain] === undefined).length,
    required: REQUIRED_LABEL_COUNT,
    exitCriterionMet: labelled.length >= REQUIRED_LABEL_COUNT,
    unlabelledDomains: domains.filter((domain) => labels[domain] === undefined),
    labellers: [...labellers].sort(),
  };
}

/**
 * What a human needs on screen to decide, assembled from the frozen evidence.
 *
 * Read-only and offline. No model is asked for a summary, because a model's
 * summary of the evidence is not the evidence, and a labeller nudged by one is
 * no longer an independent ground truth.
 */
export function labellingBrief(fixtureSet: string, domain: string): string {
  const { fixture, label, split } = loadFixture(fixtureSet, domain);
  const lines: string[] = [
    `fixture set   ${fixture.fixture_set}`,
    `domain        ${fixture.canonical_domain}`,
    `fixture id    ${fixture.fixture_id}`,
    `split         ${split ?? '(unassigned)'}`,
    `label         ${label === undefined ? '(unlabelled)' : `${label.label} by ${label.labelled_by}`}`,
    `pages         ${fixture.pages.length}`,
    '',
  ];

  for (const page of fixture.pages) {
    const signals = page.signals;
    lines.push(`--- ${page.page_kind ?? 'page'}: ${page.url}`);
    lines.push(
      `    status ${page.http_status ?? 'null'}   robots_allowed ${page.robots_allowed}   ` +
        `text ${page.text === null ? 'none' : `${page.text.length} chars`}`,
    );
    lines.push(
      signals === null
        ? '    tier A: no scan (unknown, which is not the same as absent)'
        : `    tier A: paid_search_tag ${signals.paid_search_tag}, ga4 ${signals.analytics_ga4}, ` +
          `gtm ${signals.tag_manager}, call_tracking ${signals.call_tracking}, ` +
          `tel ${signals.tel_link}, form ${signals.contact_form}, ` +
          `viewport ${signals.responsive_viewport}, locations ${signals.location_page_links ?? 'null'}, ` +
          `copyright ${signals.copyright_year ?? 'null'}`,
    );
    if (page.text !== null) {
      lines.push('');
      lines.push(
        page.text
          .split('\n')
          .map((line) => `    ${line}`)
          .join('\n'),
      );
    }
    lines.push('');
  }

  return lines.join('\n');
}
